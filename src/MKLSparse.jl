module MKLSparse

using LinearAlgebra, SparseArrays
using LinearAlgebra: BlasInt, BlasFloat, checksquare
using MKL_jll: libmkl_rt, MKL_jll

"""
    is_available() -> Bool

True iff Intel MKL has a binary for the host platform (no aarch64 / Apple
Silicon support, no PowerPC). When `false`, calls into MKL Sparse BLAS routines
raise — but `using MKLSparse` still succeeds so other packages may import the
module unconditionally and gate behind this check at runtime.
"""
is_available() = MKL_jll.is_available()

# counts total MKL Sparse API calls (for testing purposes)
global const __mklsparse_calls_count = Ref(0)

# increments to the `__mklsparse_calls_count` variable
function _log_mklsparse_call(fname)
    #@debug "$fname called"
    __mklsparse_calls_count[] += 1
end

# common MKL definitions from mkl_service.h, see also MKL.jl

@enum Threading begin
    THREADING_INTEL
    THREADING_SEQUENTIAL
    THREADING_PGI
    THREADING_GNU
    THREADING_TBB
end

@enum Interface begin
    INTERFACE_LP64
    INTERFACE_ILP64
    INTERFACE_GNU
end

function set_threading_layer(layer::Threading = THREADING_INTEL)
    err = @ccall libmkl_rt.MKL_Set_Threading_Layer(layer::Cint)::Cint
    (err == -1) && error("MKL_Set_Threading_Layer() returned -1")
    return nothing
end

function set_interface_layer(interface::Interface = INTERFACE_LP64)
    err = @ccall libmkl_rt.MKL_Set_Interface_Layer(interface::Cint)::Cint
    (err == -1) && error("MKL_Set_Interface_Layer() returned -1")
    return nothing
end

# initialize the MKL interface upon module initialization. Skipped when MKL
# itself is unavailable on the host platform (e.g. aarch64 / Apple Silicon)
# so `using MKLSparse` does not throw on those hosts.
function __init__()
    is_available() || return nothing
    set_interface_layer(INTERFACE_LP64)
    return nothing
end

